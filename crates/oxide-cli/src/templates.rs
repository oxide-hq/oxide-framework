//! File templates, embedded at compile time, and the `{{key}}` renderer.

macro_rules! templates {
    ($($name:ident => $path:literal),* $(,)?) => {
        $(pub(crate) const $name: &str = include_str!(concat!("../templates/", $path));)*

        /// Every template, for tests that check them all.
        #[cfg(test)]
        pub(crate) const ALL: &[(&str, &str)] = &[$(($path, $name)),*];
    };
}

