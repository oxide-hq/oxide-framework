/// The Oxide Eloquent Rust skill, as maintained for the framework repository.
const SKILL: &str = include_str!("../../../.claude/skills/oxide-eloquent-rust/SKILL.md");

/// Where the repository's skill talks about the framework repository itself, and what an
/// application's copy says instead.
const SKILL_REWRITES: &[(&str, &str)] = &[
    (
        "How to write code in the Oxide framework repository",
        "How to write code in this Oxide application",
    ),
    (" in this workspace,", " in this application,"),
    (
        "Code in this repository should read like a Laravel\napp",
        "Code in this application should read like a Laravel\napp",
    ),
    (
        " ORM cases go in `crates/oxide-orm/tests/suite`, which runs against SQLite and PostgreSQL.",
        "",
    ),
];

/// The section of the skill that only applies to the framework repository.
const SKILL_REPO_SECTION: (&str, &str) = ("## 7. Repository conventions", "## Review checklist");

/// Replaces every `{{key}}` in `template`.
pub(crate) fn render(template: &str, vars: &[(&str, &str)]) -> String {
    let mut out = template.to_owned();
    for (key, value) in vars {
        out = out.replace(&format!("{{{{{key}}}}}"), value);
    }
    out
}

/// The skill for an application: framework-repository details rewritten or removed.
pub(crate) fn app_skill() -> String {
    let mut skill = SKILL.to_owned();
    for (from, to) in SKILL_REWRITES {
        skill = skill.replace(from, to);
    }
    let (start, end) = SKILL_REPO_SECTION;
    if let (Some(from), Some(to)) = (skill.find(start), skill.find(end)) {
        skill.replace_range(from..to, "");
    }
    skill
}

/// The skill as a Cursor rule, in the format `scripts/sync-agent-rules.sh` writes.
pub(crate) fn cursor_rule(skill: &str) -> String {
    let description = skill
        .lines()
        .find_map(|line| line.strip_prefix("description: "))
        .unwrap_or_default();
    // Drop the skill's own frontmatter: the first two `---` lines and everything between.
    let body = skill.splitn(3, "---\n").nth(2).unwrap_or(skill);
    format!(
        "---\ndescription: {description}\nglobs: [\"**/*.rs\", \"**/Cargo.toml\"]\nalwaysApply: false\n---\n\
         <!-- Generated by `oxide new` from .claude/skills/oxide-eloquent-rust/SKILL.md. -->\n{body}"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_replaces_every_occurrence() {
        assert_eq!(
            render("{{a}}-{{b}}-{{a}}", &[("a", "x"), ("b", "y")]),
            "x-y-x"
        );
    }

    #[test]
    fn templates_only_use_known_placeholders() {
        let known = [
            "name",
            "crate_name",
            "default_database_url",
            "mailer",
            "database_url_fn",
            "health_context",
            "database_notes",
            "data_rows",
            "database_config",
            "database_section",
            "table",
            "model",
            "controller",
            "resource",
            "request",
            "middleware",
            "alias",
        ];
        for (path, template) in ALL {
            let mut rest = *template;
            while let Some(start) = rest.find("{{") {
                let end = rest[start..]
                    .find("}}")
                    .map_or(rest.len(), |end| start + end);
                let key = &rest[start + 2..end];
                assert!(
                    known.contains(&key),
                    "{path} uses unknown placeholder `{key}`"
                );
                rest = &rest[end..];
            }
        }
    }

    #[test]
    fn the_app_skill_drops_repository_details() {
        for (from, _) in SKILL_REWRITES {
            assert!(SKILL.contains(from), "SKILL.md no longer contains {from:?}");
        }
        let (start, end) = SKILL_REPO_SECTION;
        assert!(SKILL.contains(start) && SKILL.contains(end));

        let skill = app_skill();
        assert!(!skill.contains("Repository conventions"));
        assert!(!skill.contains("framework repository"));
        assert!(skill.contains("## Review checklist"));
        assert!(skill.starts_with("---\nname: oxide-eloquent-rust\n"));

        let rule = cursor_rule(&skill);
        assert!(rule.starts_with("---\ndescription: How to write code in this Oxide application"));
        assert!(rule.contains("alwaysApply: false\n---\n<!-- Generated by `oxide new`"));
        assert!(rule.contains("\n# Oxide Eloquent Rust\n"));
        assert_eq!(rule.matches("\n---\n").count(), 1);
    }
}
